#!/usr/bin/env bash
# The names nginx answers to with the web UI, the API, link protection and the
# Rspamd UI: CRASSOSTREA_HOSTNAME, the certificate's ADDITIONAL_SAN (unless
# ONLY_CRASSOSTREA_HOSTNAME, like system/libexec/acme) and the host of
# WEB_PUBLIC_URL. Requests for any other name, or for an address, get 404
# from nginx's default server; it answers only ACME challenges, for every
# name, because a name is validated before it is configured (staging tests,
# a new hostname).
#
# Sourced by common.sh, and deployed to /usr/local/lib/crassostrea/lib for
# system/libexec/set-hostname and tls-apply, which change the names and
# rewrite NGINX_NAMES_CONF without a configure.sh run. Uses the variables
# above from the caller's environment.

NGINX_NAMES_CONF=/etc/nginx/crassostrea-server-names.conf

# The names, one per line; what is no valid server name is left out
nginx_server_names() {
  local -a names extra
  local name url
  names=("${CRASSOSTREA_HOSTNAME}")
  if [[ ! ${ONLY_CRASSOSTREA_HOSTNAME:-n} =~ ^([yY]|[yY][eE][sS]|[tT][rR][uU][eE]|1)$ ]]; then
    IFS=', ' read -r -a extra <<< "${ADDITIONAL_SAN:-}"
    names+=("${extra[@]}")
  fi
  if [[ -n ${WEB_PUBLIC_URL:-} ]]; then
    url=${WEB_PUBLIC_URL#*://}
    url=${url%%/*}
    names+=("${url%%:*}")
  fi
  for name in "${names[@]}"; do
    name=${name,,}
    [[ ${name} =~ ^(\*\.)?[a-z0-9]([a-z0-9.-]*[a-z0-9])?$ ]] && echo "${name}"
  done | awk '!seen[$0]++'
}

# The content of NGINX_NAMES_CONF, included by the server of the web UI
nginx_names_conf() {
  echo "# Generated by system/configure.sh - do not edit (also written by set-hostname and tls-apply)"
  local names
  names=$(nginx_server_names | tr '\n' ' ' | sed 's/ $//')
  # "_" matches no request: without a valid name only the default server answers
  echo "server_name ${names:-_};"
}

# For the root services: rewrite NGINX_NAMES_CONF and reload nginx if the
# names changed and nginx accepts them (else the previous file is restored)
nginx_update_names() {
  local file=${NGINX_NAMES_CONF} tmp
  [[ -f ${file} ]] || return 0
  tmp=$(mktemp "${file}.XXXXXX") || return 1
  nginx_names_conf > "${tmp}"
  if cmp -s "${tmp}" "${file}"; then
    rm -f "${tmp}"
    return 0
  fi
  cp -a "${file}" "${file}.previous"
  chmod 0644 "${tmp}"
  mv "${tmp}" "${file}"
  command -v restorecon > /dev/null && restorecon "${file}" > /dev/null 2>&1
  if nginx -t > /dev/null 2>&1; then
    rm -f "${file}.previous"
    systemctl reload nginx.service 2> /dev/null || true
  else
    mv "${file}.previous" "${file}"
    echo "nginx refused the names $(nginx_server_names | tr '\n' ' '); the previous ones stay" >&2
    return 1
  fi
}
