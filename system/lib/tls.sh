#!/usr/bin/env bash
# The oldest TLS version nginx (HTTPS_TLS_MIN) and Postfix's smtpd
# (SMTP_TLS_MIN) accept: 1.2 (the default), 1.1 or 1.0. Sourced by common.sh,
# and deployed to /usr/local/lib/crassostrea/lib for system/libexec/tls-apply.
#
# TLS 1.0 and 1.1 need more than nginx's ssl_protocols and Postfix's
# smtpd_tls_protocols: the system crypto policy (TLS.MinProtocol = TLSv1.2,
# security level 2, no SHA-1 signatures) refuses them in every program, its
# LEGACY policy included. A service that accepts them gets its own OpenSSL
# configuration (TLS_LEGACY_CNF): nginx through OPENSSL_CONF (a systemd
# drop-in), Postfix through tls_config_file. Postfix's outbound connections
# keep smtp_tls_protocols >= TLSv1.2.

TLS_LEGACY_CNF=/etc/crassostrea/tls/openssl-legacy.cnf
TLS_NGINX_DROPIN=/etc/systemd/system/nginx.service.d/crassostrea-tls.conf

tls_valid_min() {
  [[ $1 == 1.0 || $1 == 1.1 || $1 == 1.2 ]]
}

tls_legacy() {
  [[ $1 == 1.0 || $1 == 1.1 ]]
}

# nginx ssl_protocols for a minimum version
tls_nginx_protocols() {
  case $1 in
    1.0) echo "TLSv1 TLSv1.1 TLSv1.2 TLSv1.3" ;;
    1.1) echo "TLSv1.1 TLSv1.2 TLSv1.3" ;;
    *) echo "TLSv1.2 TLSv1.3" ;;
  esac
}

# Postfix smtpd_tls_protocols for a minimum version
tls_postfix_protocols() {
  case $1 in
    1.0) echo ">=TLSv1" ;;
    1.1) echo ">=TLSv1.1" ;;
    *) echo ">=TLSv1.2" ;;
  esac
}

# Postfix tls_config_file: the system configuration unless a legacy version is on
tls_postfix_config_file() {
  if tls_legacy "$1"; then echo "${TLS_LEGACY_CNF}"; else echo default; fi
}

tls_legacy_cnf() {
  cat <<'CNF'
# Generated by the Crassostrea gateway (system/lib/tls.sh): the OpenSSL
# configuration of a service that accepts TLS 1.0/1.1 (Settings ->
# Certificates & TLS). Replaces the system crypto policy for that service:
# security level 0 and SHA-1 signatures, which these versions need. Which
# versions are accepted is set by the service itself.
openssl_conf = openssl_init

[openssl_init]
ssl_conf = ssl_module
alg_section = evp_properties

[evp_properties]
rh-allow-sha1-signatures = yes

[ssl_module]
system_default = tls_legacy

[tls_legacy]
MinProtocol = TLSv1
CipherString = DEFAULT:@SECLEVEL=0
CNF
}

tls_nginx_dropin() {
  cat <<DROPIN
# Generated by the Crassostrea gateway (system/lib/tls.sh): HTTPS accepts
# TLS ${HTTPS_TLS_MIN}, which the system crypto policy refuses
[Service]
Environment=OPENSSL_CONF=${TLS_LEGACY_CNF}
DROPIN
}
