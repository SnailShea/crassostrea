-- Link protection of the web UI (Link protection page), from
-- link_protection.json (data/web/crassostrea/services/links.py): the http and
-- https links of inbound mail whose recipients are all in domains with link
-- protection are rewritten to <base><id>; the web UI looks the link up in
-- Valkey (sf_link:<id>, kept ttl seconds) when it is clicked, checks it
-- against block lists and redirects or warns. Not rewritten: mail from the
-- relay networks, rejected mail, signed or encrypted mail (S/MIME, PGP),
-- links to exempt hosts and the gateway itself, and messages larger than
-- max_size. If Valkey cannot store the links, the message stays as it is.
local rspamd_trie = require "rspamd_trie"
local rspamd_text = require "rspamd_text"
local rspamd_cryptobox_hash = require "rspamd_cryptobox_hash"
local lua_mime = require "lua_mime"
local link_policy = {domains = {}, exempt = {}}
local LINK_MAX = 500

rspamd_config:add_map{
  url = rspamd_paths['LOCAL_CONFDIR'] .. '/custom/link_protection.json',
  description = "Link protection of the web UI",
  type = "callback",
  callback = function(data)
    local parser = ucl.parser()
    local ok, err = parser:parse_string(data)
    if not ok then
      rspamd_logger.errx(rspamd_config, 'cannot parse link_protection.json: %s', err)
      return
    end
    local obj = parser:get_object() or {}
    local policy = {domains = {}, exempt = {}, base = obj.base, ttl = tonumber(obj.ttl) or 7776000,
                    max_size = tonumber(obj.max_size) or 10485760}
    for _, domain in ipairs(obj.domains or {}) do
      policy.domains[tostring(domain):lower()] = true
    end
    for _, host in ipairs(obj.exempt or {}) do
      policy.exempt[#policy.exempt + 1] = tostring(host):lower()
    end
    link_policy = policy
  end
}

local link_store = sf_redis and lua_redis.add_redis_script([[
for i, key in ipairs(KEYS) do
  redis.call('SET', key, ARGV[i], 'EX', ARGV[#ARGV])
end
return #KEYS
]], sf_redis)

local function link_host(url)
  local authority = url:match('^[%a][%w+.-]*://([^/%?#]*)')
  if not authority then
    return nil
  end
  return (authority:gsub('^.*@', ''):gsub(':%d*$', ''):lower())
end

local function link_exempt(host, policy)
  for _, exempt in ipairs(policy.exempt) do
    if host == exempt or host:sub(-(#exempt + 1)) == '.' .. exempt then
      return true
    end
  end
  return false
end

-- The links of a text part: {raw text in the part = the URL it stands for}
local function link_candidates(content, is_html, found)
  if is_html then
    for _, raw in content:gmatch('[hH][rR][eE][fF]%s*=%s*(["\'])%s*(.-)%s*%1') do
      if raw:match('^[hH][tT][tT][pP][sS]?://') then
        found[raw] = raw:gsub('&[aA][mM][pP];', '&'):gsub('&#0*38;', '&'):gsub('&#[xX]0*26;', '&')
      end
    end
  else
    for raw in content:gmatch('[hH][tT][tT][pP][sS]?://[^%s<>"\'%[%]]+') do
      raw = raw:gsub('[%.,;:!%?%)]+$', '')
      found[raw] = raw
    end
  end
end

rspamd_config:register_symbol({
  name = 'LINKS_REWRITTEN',
  type = 'postfilter',
  score = 0.0,
  flags = 'nostat',
  description = 'Links rewritten by the link protection of the web UI',
  callback = function(task)
    local policy = link_policy
    if not link_store or not policy.base or next(policy.domains) == nil then
      return
    end
    local action = task:get_metric_action()
    if action == 'reject' or action == 'soft reject' then
      return
    end
    local ip = task:get_from_ip()
    if ip and ip:is_valid() and relay_networks:get_key(ip) then
      return
    end
    local rcpts = task:get_recipients('smtp') or {}
    if #rcpts == 0 then
      return
    end
    for _, rcpt in ipairs(rcpts) do
      if not policy.domains[(rcpt.domain or ''):lower()] then
        return
      end
    end
    if task:get_size() > policy.max_size then
      return
    end
    for _, part in ipairs(task:get_parts() or {}) do
      local mtype, subtype = part:get_type()
      mtype, subtype = (mtype or ''):lower(), (subtype or ''):lower()
      if (mtype == 'multipart' and (subtype == 'signed' or subtype == 'encrypted'))
          or (mtype == 'application' and (subtype == 'pkcs7-mime' or subtype == 'x-pkcs7-mime'
          or subtype == 'pgp-encrypted')) then
        return
      end
    end
    local base_host = link_host(policy.base)
    local found = {}
    for _, part in ipairs(task:get_text_parts() or {}) do
      local content = part:get_content('raw_utf')
      if content then
        link_candidates(tostring(content), part:is_html(), found)
      end
    end
    local patterns, replacements, keys, urls = {}, {}, {}, {}
    local ids = {}
    for raw, url in pairs(found) do
      local host = link_host(url)
      if host and host ~= base_host and not link_exempt(host, policy) and #patterns < LINK_MAX then
        local id = rspamd_cryptobox_hash.create_specific('sha256', url):hex():sub(1, 24)
        patterns[#patterns + 1] = raw
        replacements[#replacements + 1] = policy.base .. id
        if not ids[id] then
          ids[id] = true
          keys[#keys + 1] = 'sf_link:' .. id
          urls[#urls + 1] = url
        end
      end
    end
    if #patterns == 0 then
      return
    end
    urls[#urls + 1] = tostring(policy.ttl)
    lua_redis.exec_redis_script(link_store, {task = task, is_write = true, key = keys[1]}, function(err)
      if err then
        rspamd_logger.errx(task, 'links not rewritten: cannot store them: %s', err)
        return
      end
      local rewrite = lua_mime.multipattern_text_replace(task, rspamd_trie.create(patterns), replacements)
      if not rewrite or not rewrite.has_matches then
        return
      end
      local nl = task:get_newlines_type() == 'lf' and '\n' or '\r\n'
      local out, seen_cte = {}, false
      task:headers_foreach(function(name, hdr)
        local lname = name:lower()
        if rewrite.need_rewrite_ct and lname == 'content-type' then
          out[#out + 1] = string.format('Content-Type: %s/%s; charset=utf-8%s',
            rewrite.new_ct.type, rewrite.new_ct.subtype, nl)
        elseif rewrite.need_rewrite_ct and lname == 'content-transfer-encoding' then
          out[#out + 1] = string.format('Content-Transfer-Encoding: %s%s', rewrite.new_cte or 'quoted-printable', nl)
          seen_cte = true
        else
          out[#out + 1] = hdr.raw:gsub('\r?\n?$', '') .. nl
        end
      end, {full = true})
      if rewrite.need_rewrite_ct and not seen_cte then
        out[#out + 1] = string.format('Content-Transfer-Encoding: %s%s', rewrite.new_cte or 'quoted-printable', nl)
      end
      out[#out + 1] = string.format('X-Link-Protection: %d link(s) checked when clicked%s', #keys, nl)
      out[#out + 1] = nl
      for _, piece in ipairs(rewrite.out) do
        out[#out + 1] = piece[1]
        if piece[2] then
          out[#out + 1] = nl
        end
      end
      task:set_message(rspamd_text.fromtable(out))
      -- through the milter only the body is replaced: header changes are
      -- milter actions of their own
      local milter = {add_headers = {['X-Link-Protection'] = string.format('%d link(s) checked when clicked',
                                                                            #keys)}}
      if rewrite.need_rewrite_ct then
        milter.remove_headers = {['Content-Type'] = 0, ['Content-Transfer-Encoding'] = 0}
        milter.add_headers['Content-Type'] = string.format('%s/%s; charset=utf-8', rewrite.new_ct.type,
                                                           rewrite.new_ct.subtype)
        milter.add_headers['Content-Transfer-Encoding'] = rewrite.new_cte or 'quoted-printable'
      end
      task:set_milter_reply(milter)
      task:insert_result('LINKS_REWRITTEN', 1.0, tostring(#keys))
    end, keys, urls)
  end
})

-- Hash lookups of attachments (Attachments page,
-- data/web/crassostrea/services/hashcheck.py): the SHA-256 (MD5 for Team
-- Cymru) of each attachment is looked up in the Malware Hash Registry of
-- Team Cymru (DNS), MalwareBazaar and VirusTotal, as enabled in
-- attachment_analysis.json. The API keys are in Valkey (sf_hashcheck_keys),
-- not in a map file. Verdicts are cached in Valkey (sf_hash:<source>:<sha256>,
-- "0" clean or "1:<detail>"), VirusTotal requests are limited per minute,
-- and detections are kept for the page (sf_hash_hits). Only hashes leave
-- the gateway, never the files; a lookup that fails counts as clean.
local rspamd_http = require "rspamd_http"
local hash_policy = {}
local HASH_MAX_PARTS = 20

rspamd_config:add_map{
  url = rspamd_paths['LOCAL_CONFDIR'] .. '/custom/attachment_analysis.json',
  description = "Attachment hash lookups of the web UI",
  type = "callback",
  callback = function(data)
    local parser = ucl.parser()
    local ok, err = parser:parse_string(data)
    if not ok then
      rspamd_logger.errx(rspamd_config, 'cannot parse attachment_analysis.json: %s', err)
      return
    end
    hash_policy = parser:get_object() or {}
  end
}

local hash_prepare = sf_redis and lua_redis.load_redis_script_from_file(
  rspamd_paths['LOCAL_CONFDIR'] .. '/lua/hash_prepare.redis.lua', sf_redis)

local HASH_SYMBOLS = {mhr = 'HASH_CYMRU_MHR', mb = 'HASH_MALWAREBAZAAR', vt = 'HASH_VIRUSTOTAL'}

local function hash_found(task, file, source, verdict, cache)
  local malicious, detail = verdict:match('^(%d):?(.*)$')
  local settings = hash_policy[source] or {}
  if malicious == '1' then
    task:insert_result(HASH_SYMBOLS[source], tonumber(settings.score) or 0,
      string.format('%s:%s', file.name, detail))
  end
  if cache then
    lua_redis.redis_make_request(task, sf_redis, nil, true, function() end, 'SET',
      {'sf_hash:' .. source .. ':' .. file.sha256, verdict, 'EX', tostring(tonumber(hash_policy.cache) or 86400)})
    if malicious == '1' then
      local from = (task:get_from('smtp') or {})[1] or {}
      local rcpt = (task:get_recipients('smtp') or {})[1] or {}
      local entry = ucl.to_format({at = os.time(), sha256 = file.sha256, file = file.name, source = source,
                                   detail = detail, from = from.addr or '', rcpt = rcpt.addr or '',
                                   qid = task:get_queue_id() or ''}, 'json-compact')
      lua_redis.redis_make_request(task, sf_redis, nil, true, function(err)
        if not err then
          lua_redis.redis_make_request(task, sf_redis, nil, true, function() end, 'LTRIM', {'sf_hash_hits', '0', '499'})
        end
      end, 'LPUSH', {'sf_hash_hits', entry})
    end
  end
end

local function hash_lookup_mhr(task, file)
  local settings = hash_policy.mhr or {}
  task:get_resolver():resolve_txt({
    task = task,
    name = file.md5 .. '.malware.hash.cymru.com',
    callback = function(_, _, results, err)
      if err and err ~= 'requested record is not found' and err ~= 'no records with this name' then
        rspamd_logger.infox(task, 'Team Cymru MHR lookup of %s failed: %s', file.name, err)
        return
      end
      local percent = results and results[1] and tonumber(tostring(results[1]):match('^%d+%s+(%d+)'))
      if percent and percent >= (tonumber(settings.min_percent) or 10) then
        hash_found(task, file, 'mhr', string.format('1:%d%% of antivirus engines', percent), true)
      else
        hash_found(task, file, 'mhr', '0', true)
      end
    end
  })
end

local function hash_lookup_mb(task, file, key)
  rspamd_http.request({
    task = task,
    url = 'https://mb-api.abuse.ch/api/v1/',
    method = 'post',
    timeout = 5,
    headers = {['Auth-Key'] = key, ['Content-Type'] = 'application/x-www-form-urlencoded'},
    body = 'query=get_info&hash=' .. file.sha256,
    callback = function(err, code, body)
      if err or code ~= 200 then
        rspamd_logger.infox(task, 'MalwareBazaar lookup of %s failed: %s', file.name, err or code)
        return
      end
      local parser = ucl.parser()
      if not parser:parse_string(body) then
        return
      end
      local obj = parser:get_object() or {}
      if obj.query_status == 'ok' then
        local info = (obj.data or {})[1] or {}
        hash_found(task, file, 'mb', '1:' .. tostring(info.signature or 'known malware'), true)
      elseif obj.query_status == 'hash_not_found' then
        hash_found(task, file, 'mb', '0', true)
      else
        rspamd_logger.infox(task, 'MalwareBazaar lookup of %s: %s', file.name, obj.query_status)
      end
    end
  })
end

local function hash_lookup_vt(task, file, key)
  local settings = hash_policy.vt or {}
  rspamd_http.request({
    task = task,
    url = 'https://www.virustotal.com/api/v3/files/' .. file.sha256,
    timeout = 5,
    headers = {['x-apikey'] = key},
    callback = function(err, code, body)
      if err then
        rspamd_logger.infox(task, 'VirusTotal lookup of %s failed: %s', file.name, err)
      elseif code == 404 then
        hash_found(task, file, 'vt', '0', true)
      elseif code == 200 then
        local parser = ucl.parser()
        if not parser:parse_string(body) then
          return
        end
        local stats = (((parser:get_object() or {}).data or {}).attributes or {}).last_analysis_stats or {}
        local malicious = tonumber(stats.malicious) or 0
        if malicious >= (tonumber(settings.min_engines) or 3) then
          hash_found(task, file, 'vt', string.format('1:%d engines', malicious), true)
        else
          hash_found(task, file, 'vt', '0', true)
        end
      else
        rspamd_logger.infox(task, 'VirusTotal lookup of %s: HTTP %s', file.name, code)
      end
    end
  })
end

local hash_id = rspamd_config:register_symbol({
  name = 'SF_HASH_LOOKUP',
  type = 'callback',
  flags = 'nostat',
  callback = function(task)
    local policy = hash_policy
    local mhr, mb, vt = (policy.mhr or {}).enabled, (policy.mb or {}).enabled, (policy.vt or {}).enabled
    if not hash_prepare or not (mhr or mb or vt) then
      return
    end
    local files, seen = {}, {}
    for _, part in ipairs(task:get_parts() or {}) do
      if #files >= HASH_MAX_PARTS then
        break
      end
      local mtype = (part:get_type() or ''):lower()
      if mtype ~= 'multipart' and mtype ~= 'message' and not part:is_text()
          and part:get_length() >= 64 and part:get_length() <= (tonumber(policy.max_size) or 52428800) then
        local content = part:get_content()
        local sha256 = rspamd_cryptobox_hash.create_specific('sha256', content):hex()
        if not seen[sha256] then
          seen[sha256] = true
          files[#files + 1] = {name = part:get_filename() or 'unnamed', sha256 = sha256,
                               md5 = rspamd_cryptobox_hash.create_specific('md5', content):hex()}
        end
      end
    end
    if #files == 0 then
      return
    end
    local args = {tostring(math.floor(os.time() / 60)), tostring(tonumber((policy.vt or {}).per_minute) or 4)}
    for _, file in ipairs(files) do
      args[#args + 1] = file.sha256
    end
    lua_redis.exec_redis_script(hash_prepare, {task = task, is_write = true}, function(err, data)
      if err or type(data) ~= 'table' then
        rspamd_logger.errx(task, 'attachment hashes not looked up: %s', err or 'no answer')
        return
      end
      local mb_key, vt_key = tostring(data[1] or ''), tostring(data[2] or '')
      for i, file in ipairs(files) do
        local base = 2 + (i - 1) * 4
        local cached = {mhr = tostring(data[base + 1] or ''), mb = tostring(data[base + 2] or ''),
                        vt = tostring(data[base + 3] or '')}
        local vt_allowed = tostring(data[base + 4] or '0') == '1'
        if mhr then
          if cached.mhr ~= '' then hash_found(task, file, 'mhr', cached.mhr) else hash_lookup_mhr(task, file) end
        end
        if mb and mb_key ~= '' then
          if cached.mb ~= '' then hash_found(task, file, 'mb', cached.mb) else hash_lookup_mb(task, file, mb_key) end
        end
        if vt and vt_key ~= '' then
          if cached.vt ~= '' then
            hash_found(task, file, 'vt', cached.vt)
          elseif vt_allowed then
            hash_lookup_vt(task, file, vt_key)
          end
        end
      end
    end, {}, args)
  end
})
for source, symbol in pairs(HASH_SYMBOLS) do
  rspamd_config:register_symbol({name = symbol, type = 'virtual', parent = hash_id, score = 1.0, group = 'antivirus',
                                 description = 'An attachment is known malware (' .. source .. ')'})
end

-- Content rules of the web UI (Content rules page), from content_rules.json
-- (data/web/crassostrea/services/content_rules.py). A rule looks at one part
-- of a message (subject, From, envelope sender, recipients, a header, the
-- text, URLs or attachment names), matches "contains" or "equals" (ASCII
-- case ignored) or a regular expression, and adds its score (CONTENT_RULE),
-- rejects the message (CONTENT_RULE_REJECT; inbound mail is quarantined) or
-- adds X-Content-Rule. A prefilter, so a reject rule always applies.
local content_rules = {}

rspamd_config:add_map{
  url = rspamd_paths['LOCAL_CONFDIR'] .. '/custom/content_rules.json',
  description = "Content rules of the web UI",
  type = "callback",
  callback = function(data)
    local parser = ucl.parser()
    local ok, err = parser:parse_string(data)
    if not ok then
      rspamd_logger.errx(rspamd_config, 'cannot parse content_rules.json: %s', err)
      return
    end
    local rules = {}
    for _, rule in ipairs((parser:get_object() or {}).rules or {}) do
      if rule.match == 'regex' then
        rule.re = rspamd_regexp.create(rule.value or '', '')
      else
        rule.needle = tostring(rule.value or ''):lower()
      end
      if rule.match ~= 'regex' or rule.re then
        rules[#rules + 1] = rule
      else
        rspamd_logger.errx(rspamd_config, 'content rule %s: invalid regular expression, ignored', rule.name)
      end
    end
    content_rules = rules
  end
}

local function content_values(task, field, header, cache)
  local key = field .. ':' .. (header or '')
  if cache[key] then
    return cache[key]
  end
  local values = {}
  if field == 'subject' then
    values = {task:get_subject() or ''}
  elseif field == 'from' then
    for _, addr in ipairs(task:get_from('mime') or {}) do
      values[#values + 1] = (addr.name and addr.name ~= '' and (addr.name .. ' <' .. (addr.addr or '') .. '>'))
          or addr.addr or ''
    end
  elseif field == 'envelope_from' then
    local from = (task:get_from('smtp') or {})[1]
    values = {from and from.addr or ''}
  elseif field == 'recipient' then
    for _, rcpt in ipairs(task:get_recipients('smtp') or {}) do
      values[#values + 1] = rcpt.addr or ''
    end
  elseif field == 'header' then
    for _, h in ipairs(task:get_header_full(header or '') or {}) do
      values[#values + 1] = h.decoded or h.value or ''
    end
  elseif field == 'body' then
    for _, part in ipairs(task:get_text_parts() or {}) do
      local content = part:get_content()
      if content then
        values[#values + 1] = tostring(content)
      end
    end
  elseif field == 'url' then
    for _, url in ipairs(task:get_urls() or {}) do
      values[#values + 1] = url:get_text()
    end
  elseif field == 'attachment' then
    for _, part in ipairs(task:get_parts() or {}) do
      local name = part:get_filename()
      if name then
        values[#values + 1] = name
      end
    end
  end
  cache[key] = values
  return values
end

local function content_matches(rule, value)
  if rule.match == 'regex' then
    return rule.re:match(value)
  end
  local lower = tostring(value):lower()
  if rule.match == 'equals' then
    return lower == rule.needle
  end
  return lower:find(rule.needle, 1, true) ~= nil
end

local content_id = rspamd_config:register_symbol({
  name = 'SF_CONTENT_RULES',
  type = 'prefilter',
  flags = 'empty,nostat',
  callback = function(task)
    if #content_rules == 0 or task:has_pre_result() then
      return
    end
    local ip = task:get_from_ip()
    local outbound = ip and ip:is_valid() and relay_networks:get_key(ip) and true or false
    local cache, tagged, rejected = {}, {}, nil
    for _, rule in ipairs(content_rules) do
      if rule.direction == 'both' or (rule.direction == 'outbound') == outbound then
        for _, value in ipairs(content_values(task, rule.field, rule.header, cache)) do
          if content_matches(rule, value) then
            if rule.action == 'reject' then
              rejected = rejected or rule
            elseif rule.action == 'tag' then
              tagged[#tagged + 1] = rule.name
            else
              task:insert_result('CONTENT_RULE', tonumber(rule.score) or 0, rule.name)
            end
            break
          end
        end
      end
      if rejected then
        break
      end
    end
    if rejected then
      task:insert_result('CONTENT_RULE_REJECT', 1.0, rejected.name)
      task:set_pre_result('reject', rejected.message ~= '' and rejected.message
          or 'Message rejected by the content rules', 'content_rules')
    elseif #tagged > 0 then
      task:insert_result('CONTENT_RULE_TAG', 1.0, tagged)
      task:set_milter_reply({add_headers = {['X-Content-Rule'] = table.concat(tagged, ', ')}})
    end
  end
})
for _, def in ipairs({{'CONTENT_RULE', 1.0, 'A content rule of the web UI matched (its score)'},
                      {'CONTENT_RULE_REJECT', 0.0, 'A content rule of the web UI rejected the message'},
                      {'CONTENT_RULE_TAG', 0.0, 'A content rule of the web UI tagged the message'}}) do
  rspamd_config:register_symbol({name = def[1], type = 'virtual', parent = content_id, score = def[2],
                                 description = def[3]})
end

-- Mail for the web UI (intake.json, data/web/crassostrea/services/maps.py):
-- DMARC and TLS reports to reports@<hostname> (services/reports.py), and
-- messages users report to spam@ and ham@<hostname> (services/user_reports.py).
-- Postfix accepts these addresses and then discards the mail; it is not
-- filtered here but handed to the web UI's internal API, with the envelope
-- and the client for its check of who reported.
local intake_addresses = {}
local INTAKE_PATHS = {reports = '/internal/reports', spam = '/internal/learn/spam', ham = '/internal/learn/ham'}

rspamd_config:add_map{
  url = rspamd_paths['LOCAL_CONFDIR'] .. '/custom/intake.json',
  description = "Addresses of the web UI",
  type = "callback",
  callback = function(data)
    local parser = ucl.parser()
    if not parser:parse_string(data) then
      return
    end
    local addresses = {}
    for address, kind in pairs((parser:get_object() or {}).addresses or {}) do
      if INTAKE_PATHS[kind] then
        addresses[tostring(address):lower()] = kind
      end
    end
    intake_addresses = addresses
  end
}

-- The kind of mail for the web UI if every recipient is one address of it
local function intake_kind(task)
  local rcpts = task:get_recipients('smtp') or {}
  local kind
  for _, rcpt in ipairs(rcpts) do
    local this = intake_addresses[(rcpt.addr or ''):lower()]
    if not this or (kind and kind ~= this) then
      return nil
    end
    kind = this
  end
  return kind
end

rspamd_config:register_symbol({
  name = 'SF_INTAKE',
  type = 'prefilter',
  priority = 9,
  flags = 'empty,nostat',
  callback = function(task)
    if intake_kind(task) then
      task:set_flag('no_stat')
      task:set_pre_result('no action', 'mail for the web UI', 'intake')
    end
  end
})

-- Idempotent, not a postfilter: the pre-result of SF_INTAKE makes rspamd
-- skip the filters and postfilters, only idempotent symbols still run.
rspamd_config:register_symbol({
  name = 'SF_INTAKE_EXPORT',
  type = 'idempotent',
  flags = 'empty,nostat',
  callback = function(task)
    local kind = intake_kind(task)
    if not kind then
      return
    end
    local ip = task:get_from_ip()
    local from = (task:get_from('smtp') or {})[1] or {}
    rspamd_http.request({
      task = task,
      url = 'http://127.0.0.1:8001' .. INTAKE_PATHS[kind],
      method = 'post',
      timeout = 30,
      headers = {['Content-Type'] = 'message/rfc822', ['X-Envelope-From'] = from.addr or '',
                 ['X-Client-IP'] = ip and ip:is_valid() and ip:to_string() or '',
                 ['X-Relay-Network'] = ip and ip:is_valid() and relay_networks:get_key(ip) and 'yes' or 'no'},
      body = task:get_content(),
      callback = function(err, code, body)
        if err or code ~= 200 then
          rspamd_logger.errx(task, '%s not handed to the web UI: %s %s', kind, err or code, body or '')
        else
          rspamd_logger.infox(task, '%s handed to the web UI: %s', kind, body)
        end
      end
    })
  end
})
