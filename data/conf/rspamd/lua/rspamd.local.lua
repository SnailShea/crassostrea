-- The direction of a message as the web UI files it (mail log, quarantine):
-- RELAY_NETWORK and RCPT_PROTECTED_DOMAIN, also set by the multimap rules of
-- local.d/multimap.conf. Those are normal checks, which rspamd skips once a
