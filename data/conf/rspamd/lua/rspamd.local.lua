rspamd_config:register_symbol({
  name = 'SF_MAIL_DIRECTION',
  type = 'prefilter',
  priority = 10,
  flags = 'empty,nostat',
  callback = function(task)
    local ip = task:get_from_ip()
    if ip and ip:is_valid() and relay_networks:get_key(ip) then
      task:insert_result('RELAY_NETWORK', 1.0, ip:to_string())
    end
    for _, rcpt in ipairs(task:get_recipients('smtp') or {}) do
      local domain = (rcpt.domain or ''):lower()
      if domain ~= '' and protected_domains:get_key(domain) then
        task:insert_result('RCPT_PROTECTED_DOMAIN', 1.0, domain)
      end
