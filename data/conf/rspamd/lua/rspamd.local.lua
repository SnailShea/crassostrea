-- Condition of the per-user settings rules generated by the web UI
-- (data/web/crassostrea/services/maps.py): returns the address only if every
-- envelope recipient is that address or one of its sub-addresses
-- (local+tag@domain). Settings apply to the whole message, so a mailbox
-- user's rules must not match a message that also goes to someone else.
local lua_selectors = require "lua_selectors"

lua_selectors.register_extractor(rspamd_config, 'sf_rcpts_owned_by', {
  get_value = function(task, args)
    local owner = args and args[1]
    if type(owner) ~= 'string' then
      return nil
    end
    local owner_local, owner_domain = owner:lower():match('^(.+)@([^@]+)$')
    if not owner_local then
      return nil
    end
    local rcpts = task:get_recipients('smtp')
    if not rcpts or #rcpts == 0 then
      return nil
    end
    for _, rcpt in ipairs(rcpts) do
      local user = (rcpt.user or ''):lower()
      if (rcpt.domain or ''):lower() ~= owner_domain then
        return nil
      end
      if user ~= owner_local and user:sub(1, #owner_local + 1) ~= owner_local .. '+' then
        return nil
      end
    end
    return owner_local .. '@' .. owner_domain, 'string'
  end,
  description = 'The given address if every SMTP recipient is it or one of its sub-addresses',
})

-- Condition of the domain allow-list and threshold rules: returns the domain
-- only if every envelope recipient is in it, so one protected domain's
-- settings never decide for recipients in another one.
lua_selectors.register_extractor(rspamd_config, 'sf_rcpts_in_domain', {
  get_value = function(task, args)
    local wanted = args and args[1]
    if type(wanted) ~= 'string' or wanted == '' then
      return nil
    end
    wanted = wanted:lower()
    local rcpts = task:get_recipients('smtp')
    if not rcpts or #rcpts == 0 then
      return nil
    end
    for _, rcpt in ipairs(rcpts) do
      if (rcpt.domain or ''):lower() ~= wanted then
        return nil
      end
    end
    return wanted, 'string'
  end,
  description = 'The given domain if every SMTP recipient is in it',
})

