local outbound_limits = rspamd_config:add_map{
  url = rspamd_paths['LOCAL_CONFDIR'] .. '/custom/outbound_limits.map',
  description = "Outbound limits of the web UI",
  type = "map"
}
local PERIOD_NAMES = {[60] = 'minute', [3600] = 'hour', [86400] = 'day'}

local function outbound_rule(sender, domain)
  for _, key in ipairs({sender, domain and ('@' .. domain) or '*', '*'}) do
    local value = outbound_limits:get_key(key)
    if value then
      local limit, seconds = tostring(value):match('^(%d+):(%d+)$')
      if limit then
        return tonumber(limit), tonumber(seconds)
      end
    end
  end
  return nil
end

-- Valkey of the gateway (local.d/redis.conf) for the checks below
local sf_redis = lua_redis.parse_redis_server('sf_gateway')
local outbound_script = sf_redis and lua_redis.load_redis_script_from_file(
  rspamd_paths['LOCAL_CONFDIR'] .. '/lua/outbound_limit.redis.lua', sf_redis)

if outbound_script then
  rspamd_config:register_symbol({
    name = 'OUTBOUND_LIMIT',
    type = 'prefilter',
    score = 0.0,
    description = 'A sender of the relay networks reached its outbound limit',
    flags = 'empty,nostat',
    augmentations = {string.format('timeout=%f', sf_redis.timeout or 0.0)},
    callback = function(task)
      if task:has_pre_result() then
        return
      end
      local ip = task:get_from_ip()
      if not ip or not ip:is_valid() or not relay_networks:get_key(ip) then
        return
      end
      local from = (task:get_from('smtp') or {})[1]
      local sender, domain
      if from and from.addr and from.addr ~= '' then
        sender, domain = from.addr:lower(), (from.domain or ''):lower()
      else
        sender = 'bounces:' .. ip:to_string()
      end
      local limit, seconds = outbound_rule(sender, domain)
      if not limit or limit <= 0 or seconds <= 0 then
        return
      end
      local n = math.max(#(task:get_recipients('smtp') or {}), 1)
      local period = PERIOD_NAMES[seconds] or string.format('%d seconds', seconds)
      if n > limit then
        task:insert_result('OUTBOUND_LIMIT', 1.0, sender)
        task:set_pre_result('reject', string.format(
          'Message rejected: %d recipients, more than the sending limit of %d per %s', n, limit, period),
          'outbound_limit')
        return
      end
      local now = os.time()
      local key = string.format('sf_rl:%d:%s:%d', seconds, sender, math.floor(now / seconds))
      lua_redis.exec_redis_script(outbound_script, {key = key, task = task, is_write = true},
        function(err, data)
          if err then
            rspamd_logger.errx(task, 'outbound limit of %s not checked: %s', sender, err)
          elseif type(data) == 'table' and tonumber(data[1]) == 0 then
            task:insert_result('OUTBOUND_LIMIT', 1.0, sender)
            task:set_pre_result('soft reject', string.format(
              'Sending limit of %d recipients per %s reached for %s, try again later', limit, period, sender),
              'outbound_limit')
          end
        end,
        {key}, {tostring(n), tostring(limit), tostring(seconds), sender, tostring(now)})
    end
  })
end

