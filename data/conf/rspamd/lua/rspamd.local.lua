-- Inbound rate limits of the web UI (Rate limits page,
-- data/web/crassostrea/services/ratelimits.py): messages per sending IP, per
-- recipient and bounces (empty sender) per recipient, counted in Valkey for
-- every node by inbound_limit.redis.lua. inbound_limits.map has
-- "<ip|rcpt|bounce> <limit>:<seconds>" lines for the limits in use. Over a
-- limit the message is deferred (4xx): the sending server retries later. The
-- relay networks (outbound limits) and rate_limit_exempt.map are exempt. If
-- Valkey cannot be asked, mail is not held up.
local inbound_limits = rspamd_config:add_map{
  url = rspamd_paths['LOCAL_CONFDIR'] .. '/custom/inbound_limits.map',
  description = "Inbound rate limits of the web UI",
  type = "map"
}
local rate_limit_exempt = rspamd_config:add_map{
  url = rspamd_paths['LOCAL_CONFDIR'] .. '/custom/rate_limit_exempt.map',
  description = "Networks without rate limits (web UI)",
  type = "radix"
}
local inbound_script = sf_redis and lua_redis.load_redis_script_from_file(
  rspamd_paths['LOCAL_CONFDIR'] .. '/lua/inbound_limit.redis.lua', sf_redis)

local function inbound_rule(kind)
  local value = inbound_limits:get_key(kind)
  if value then
    local limit, seconds = tostring(value):match('^(%d+):(%d+)$')
    if limit and tonumber(limit) > 0 and tonumber(seconds) > 0 then
      return tonumber(limit), tonumber(seconds)
    end
  end
  return nil
end

if inbound_script then
  rspamd_config:register_symbol({
    name = 'INBOUND_LIMIT',
    type = 'prefilter',
    score = 0.0,
    description = 'A sending server or a recipient reached an inbound rate limit',
    flags = 'empty,nostat',
    augmentations = {string.format('timeout=%f', sf_redis.timeout or 0.0)},
    callback = function(task)
      if task:has_pre_result() then
        return
      end
      local ip = task:get_from_ip()
      if not ip or not ip:is_valid() or relay_networks:get_key(ip) or rate_limit_exempt:get_key(ip) then
        return
      end
      local address = ip:to_string()
      if address == '127.0.0.1' or address == '::1' then
        return
      end
      local now = os.time()
      local keys, args, rules = {}, {tostring(now)}, {}
      local function add(kind, key)
        local limit, seconds = inbound_rule(kind)
        if not limit then
          return
        end
        table.insert(keys, string.format('sf_irl:%s:%d:%s:%d', kind, seconds, key, math.floor(now / seconds)))
        table.insert(args, tostring(limit))
        table.insert(args, tostring(seconds))
        table.insert(args, kind .. ':' .. key)
        table.insert(rules, {kind = kind, key = key, limit = limit, seconds = seconds})
      end
      add('ip', address)
      local from = (task:get_from('smtp') or {})[1]
      local bounce = not from or not from.addr or from.addr == ''
      for _, rcpt in ipairs(task:get_recipients('smtp') or {}) do
        if rcpt.addr and rcpt.addr ~= '' then
          add('rcpt', rcpt.addr:lower())
          if bounce then
            add('bounce', rcpt.addr:lower())
          end
        end
      end
      if #keys == 0 then
        return
      end
      lua_redis.exec_redis_script(inbound_script, {key = keys[1], task = task, is_write = true},
        function(err, data)
          if err then
            rspamd_logger.errx(task, 'inbound rate limits not checked: %s', err)
          elseif type(data) == 'table' and tonumber(data[1]) == 0 then
            local rule = rules[tonumber(data[2])]
            if not rule then
              return
            end
            local period = PERIOD_NAMES[rule.seconds] or string.format('%d seconds', rule.seconds)
            local what = rule.kind == 'ip' and 'from this server' or
              (rule.kind == 'bounce' and 'bounces to ' or 'messages to ') .. rule.key
            task:insert_result('INBOUND_LIMIT', 1.0, rule.kind .. ':' .. rule.key)
            task:set_pre_result('soft reject', string.format(
              'Rate limit of %d %s per %s reached, try again later', rule.limit,
              rule.kind == 'ip' and 'messages ' .. what or what, period), 'inbound_limit')
          end
        end,
        keys, args)
    end
  })
end

-- Outbound data loss prevention rules of the web UI (Data loss prevention
-- page), from dlp_rules.json (data/web/crassostrea/services/dlp.py): mail
-- from the relay networks whose subject, text or text attachments hold at
-- least min_matches different matches of a rule's detector
-- (dlp_detectors.lua). Of the matching rules, "reject" and "quarantine"
-- reject the message, "quarantine" also keeps it in the outbound quarantine
-- for an administrator to release (OUTBOUND_DLP_QUARANTINE), and every rule
-- is named in the symbol's options and, if delivered, in X-DLP-Match.
local ucl = require "ucl"
local rspamd_regexp = require "rspamd_regexp"
local dlp = dofile(rspamd_paths['LOCAL_CONFDIR'] .. '/lua/dlp_detectors.lua')
local dlp_rules = {}
-- Bytes of text looked at per message
local DLP_MAX_TEXT = 20 * 1048576
local DLP_TEXT_ATTACHMENTS = {csv = true, json = true, xml = true, ['x-csv'] = true}

rspamd_config:add_map{
  url = rspamd_paths['LOCAL_CONFDIR'] .. '/custom/dlp_rules.json',
  description = "Data loss prevention rules of the web UI",
  type = "callback",
  callback = function(data)
    local parser = ucl.parser()
    local ok, err = parser:parse_string(data)
    if not ok then
      rspamd_logger.errx(rspamd_config, 'cannot parse dlp_rules.json: %s', err)
      return
    end
    local rules = {}
    for _, rule in ipairs((parser:get_object() or {}).rules or {}) do
      if rule.detector == 'regex' then
        rule.re = rspamd_regexp.create(rule.pattern or '', '')
        if not rule.re then
          rspamd_logger.errx(rspamd_config, 'DLP rule %s: invalid regular expression, ignored', rule.name)
        end
      end
      if rule.detector ~= 'regex' or rule.re then
        rules[#rules + 1] = rule
      end
    end
    dlp_rules = rules
  end
}

local function dlp_texts(task)
  local texts, size = {task:get_subject() or ''}, 0
  for _, part in ipairs(task:get_parts() or {}) do
    local content
    if part:is_text() then
      content = part:get_text():get_content()
    else
      local mtype, subtype = part:get_type()
      if (mtype or ''):lower() == 'text' or DLP_TEXT_ATTACHMENTS[(subtype or ''):lower()] then
        content = part:get_content()
      end
    end
    if content then
      content = tostring(content)
      if size + #content > DLP_MAX_TEXT then
        content = content:sub(1, DLP_MAX_TEXT - size)
      end
      size = size + #content
      texts[#texts + 1] = content
      if size >= DLP_MAX_TEXT then
        break
      end
    end
  end
  return texts
end

local function dlp_applies(rule, sender, domain)
  local scope = rule.sender or ''
  return scope == '' or scope == sender or scope == domain
end

-- a prefilter: rspamd skips normal checks once a message reached the reject
-- score, and the rule's verdict must not depend on that
local dlp_id = rspamd_config:register_symbol({
  name = 'OUTBOUND_DLP',
  type = 'prefilter',
  flags = 'empty,nostat',
  score = 0.0,
  description = 'Outbound mail matched a data loss prevention rule of the web UI',
  callback = function(task)
    if #dlp_rules == 0 or task:has_pre_result() then
      return
    end
    local ip = task:get_from_ip()
    if not ip or not ip:is_valid() or not relay_networks:get_key(ip) then
      return
    end
    local from = (task:get_from('smtp') or {})[1] or {}
    local sender, domain = (from.addr or ''):lower(), (from.domain or ''):lower()
    local texts
    local matched, reject, quarantine = {}, nil, false
    for _, rule in ipairs(dlp_rules) do
      if dlp_applies(rule, sender, domain) then
        texts = texts or dlp_texts(task)
        local found, count = {}, 0
        for _, text in ipairs(texts) do
          local values
          if rule.detector == 'keywords' then
            values = dlp.keywords(text, rule.keywords or {})
          elseif rule.detector == 'regex' then
            values = dlp.regex(text, rule.re)
          elseif dlp[rule.detector] then
            values = dlp[rule.detector](text)
          end
          for value in pairs(values or {}) do
            if not found[value] then
              found[value], count = true, count + 1
            end
          end
        end
        if count >= (tonumber(rule.min_matches) or 1) then
          matched[#matched + 1] = rule.name
          if rule.action == 'reject' or rule.action == 'quarantine' then
            reject = reject or rule.name
            quarantine = quarantine or rule.action == 'quarantine'
          end
        end
      end
    end
    if #matched == 0 then
      return
    end
    task:insert_result('OUTBOUND_DLP', 1.0, matched)
    if reject then
      if quarantine then
        task:insert_result('OUTBOUND_DLP_QUARANTINE', 1.0, reject)
      end
      task:set_pre_result('reject', string.format(
        'Message rejected: it contains data that the rule "%s" does not allow to be sent', reject), 'dlp')
    else
      task:set_milter_reply({add_headers = {['X-DLP-Match'] = table.concat(matched, ', ')}})
    end
  end
})

rspamd_config:register_symbol({
  name = 'OUTBOUND_DLP_QUARANTINE',
  type = 'virtual',
  parent = dlp_id,
  score = 0.0,
  description = 'Kept in the outbound quarantine by a data loss prevention rule',
})

-- Attachment policy of the web UI (Attachments page), from
-- attachment_policy.json (data/web/crassostrea/services/maps.py): attachments
-- whose file extension is blocked, also as a file inside an archive, and
-- optionally password-protected archives, are rejected; inbound mail of
-- domains with a quarantine goes there for release. Only outbound mail from
-- the relay networks if "outbound" is set; senders (addresses, domains) in
-- "exempt" are let through.
local attachment_policy = {extensions = {}, exempt = {}}

rspamd_config:add_map{
  url = rspamd_paths['LOCAL_CONFDIR'] .. '/custom/attachment_policy.json',
  description = "Attachment policy of the web UI",
  type = "callback",
  callback = function(data)
    local parser = ucl.parser()
    local ok, err = parser:parse_string(data)
    if not ok then
      rspamd_logger.errx(rspamd_config, 'cannot parse attachment_policy.json: %s', err)
      return
    end
    local policy = parser:get_object() or {}
    local extensions, exempt = {}, {}
    for _, ext in ipairs(policy.extensions or {}) do
      extensions[tostring(ext):lower()] = true
    end
    for _, sender in ipairs(policy.exempt or {}) do
      exempt[tostring(sender):lower()] = true
    end
    attachment_policy = {extensions = extensions, exempt = exempt, archives = policy.archives,
                         encrypted = policy.encrypted, outbound = policy.outbound}
  end
}

-- The extension of a file name as Windows sees it (trailing dots and spaces
-- are dropped)
local function attachment_extension(name)
  name = tostring(name or ''):lower():gsub('[%s%.]+$', '')
  return name:match('%.([^%./\\]+)$')
end

-- a prefilter, like OUTBOUND_DLP: always checked
rspamd_config:register_symbol({
  name = 'ATTACHMENT_BLOCKED',
  type = 'prefilter',
  score = 0.0,
  description = 'An attachment is not allowed by the attachment policy of the web UI',
  callback = function(task)
    local policy = attachment_policy
    if next(policy.extensions) == nil and not policy.encrypted then
      return
    end
    local ip = task:get_from_ip()
    if not policy.outbound and ip and ip:is_valid() and relay_networks:get_key(ip) then
      return
    end
    local from = (task:get_from('smtp') or {})[1] or {}
    if policy.exempt[(from.addr or ''):lower()] or policy.exempt[(from.domain or ''):lower()] then
      return
    end
    local reason
    for _, part in ipairs(task:get_parts() or {}) do
      local filename = part:get_filename()
      local ext = attachment_extension(filename)
      if ext and policy.extensions[ext] then
        reason = string.format('%s (.%s)', filename, ext)
      elseif part:is_archive() then
        local archive = part:get_archive()
        if policy.encrypted and (archive:is_encrypted() or archive:is_unreadable()) then
          reason = string.format('%s (password-protected archive)', filename or 'archive')
        elseif policy.archives or policy.encrypted then
          for _, file in ipairs(archive:get_files_full(1000) or {}) do
            local inner = attachment_extension(file.name)
            if policy.encrypted and file.encrypted then
              reason = string.format('%s (password-protected archive)', filename or 'archive')
            elseif policy.archives and inner and policy.extensions[inner] then
              reason = string.format('%s in %s (.%s)', file.name, filename or 'archive', inner)
            end
            if reason then
              break
            end
          end
        end
      end
      if reason then
        break
      end
    end
    if reason then
      task:insert_result('ATTACHMENT_BLOCKED', 1.0, reason)
      task:set_pre_result('reject', 'Message rejected: attachment not accepted: ' .. reason, 'attachment_policy')
    end
  end
})

