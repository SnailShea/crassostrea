      return
    end
    local obj = parser:get_object() or {}
    local policy = {people = {}, domains = {}, exempt = {}, scores = {}}
    for _, person in ipairs(obj.people or {}) do
      local addresses = {}
      for _, address in ipairs(person.addresses or {}) do
        addresses[tostring(address):lower()] = true
      end
      policy.people[#policy.people + 1] = {name = person.name, addresses = addresses}
    end
    for _, domain in ipairs(obj.domains or {}) do
      policy.domains[#policy.domains + 1] = tostring(domain):lower()
    end
    for _, domain in ipairs(obj.exempt or {}) do
      policy.exempt[tostring(domain):lower()] = true
    end
    for key, value in pairs(obj.scores or {}) do
      policy.scores[key] = tonumber(value) or 0
    end
    imp_policy = policy
  end
}

local function imp_aligned(domain, other)
  domain, other = (domain or ''):lower(), (other or ''):lower()
  return domain ~= '' and other ~= '' and
      (domain == other or domain:sub(-(#other + 1)) == '.' .. other or other:sub(-(#domain + 1)) == '.' .. domain)
end

local function imp_authenticated(task, domain)
  if task:has_symbol('DMARC_POLICY_ALLOW') then
    return true
  end
  local dkim = task:get_symbol('R_DKIM_ALLOW')
  for _, sym in ipairs(dkim or {}) do
    for _, option in ipairs(sym.options or {}) do
      if imp_aligned(tostring(option):match('^([^:]+)'), domain) then
        return true
      end
    end
  end
  local envelope = (task:get_from('smtp') or {})[1]
  return task:has_symbol('R_SPF_ALLOW') and envelope ~= nil and imp_aligned(envelope.domain, domain)
end

local imp_id = rspamd_config:register_symbol({
  name = 'SF_IMPERSONATION',
  type = 'callback',
  flags = 'nostat',
  callback = function(task)
    local policy, scores = imp_policy, imp_policy.scores
    local ip = task:get_from_ip()
    if ip and ip:is_valid() and relay_networks:get_key(ip) then
      return
    end
    local from = (task:get_from('mime') or {})[1]
    if not from or not from.addr or from.addr == '' then
      return
    end
    local address, domain = from.addr:lower(), (from.domain or ''):lower()
    local protected
    for _, candidate in ipairs(policy.domains) do
      if domain == candidate or domain:sub(-(#candidate + 1)) == '.' .. candidate then
        protected = candidate
        break
      end
    end
    if protected then
      if (scores.spoof or 0) > 0 and not imp_authenticated(task, domain) then
        task:insert_result('SPOOFED_OWN_DOMAIN', scores.spoof, domain)
      end
      return
    end
    if (scores.name or 0) > 0 and from.name and from.name ~= '' then
      for _, person in ipairs(policy.people) do
        if not person.addresses[address] and imp.name_matches(from.name, person.name) then
          task:insert_result('IMPERSONATION_NAME', scores.name, person.name)
          break
        end
      end
    end
    if (scores.lookalike or 0) > 0 then
      local imitated = imp.lookalike(domain, policy.domains, policy.exempt)
      if imitated then
        task:insert_result('LOOKALIKE_DOMAIN', scores.lookalike, string.format('%s~%s', domain, imitated))
      end
    end
  end
})
